"""Build the Phase-2 Checkpoint-1 inventory: manifest, dedup log, coverage map and report.

    python -m phase2.build            # writes phase2/output/*
    python -m phase2.build --check    # build in memory, print summary only

Read-only with respect to every evidence source, Supabase and Vercel.
"""

from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path

from phase2 import paths
from phase2.classify import STATUSES, applicability_class, classify, find_conflicts
from phase2.coverage import assign_question_ids, compute_coverage, compare_with_tree, load_questions
from phase2.dedupe import content_hash, dedupe_exact
from phase2.loaders import DatasetSummary, Record, load_all

MANIFEST_SCHEMA = "phase2-checkpoint1-manifest/1"


def _row(r: Record, status: str, reasons: list[str], also_in: list[dict]) -> dict:
    return {
        "record_id": f"{r.dataset}:{r.claim_id}",
        "claim_id": r.claim_id,
        "originating_dataset": r.dataset,
        "also_present_in": also_in,
        "source_id": r.source_id,
        "source_title": r.source_title,
        "source_url": r.source_url,
        "claim_text": r.claim_text,
        "supporting_excerpt": r.excerpt,
        "locator": r.locator,
        "publication_date": r.publication_date,
        "publication_date_precision": r.publication_date_precision,
        "uc_applicability": r.uc_applicability,
        "applicability_class": applicability_class(r.uc_applicability),
        "disease_context": r.disease_context,
        "evidence_status": r.evidence_status,
        "review_status": r.review_status,
        "verification_status": r.verification_status,
        "limitations": r.limitations,
        "topic": r.topic,
        "in_production": r.in_production,
        "mapped_question_ids": r.mapped_question_ids,
        "mapping_basis": r.mapping_basis,
        "content_hash": content_hash(r),
        "status": status,
        "status_reasons": reasons,
    }


def build(records: list[Record] | None = None, summaries: list[DatasetSummary] | None = None,
          questions: list[dict] | None = None) -> dict:
    if records is None:
        records, summaries = load_all()
    questions = questions if questions is not None else load_questions()
    assign_question_ids(records)

    conflicts = find_conflicts(records)        # judged on ALL rows, before any collapse
    dd = dedupe_exact(records)

    rows = []
    for r in sorted(dd.kept, key=lambda x: (x.claim_id, paths.DATASET_PRIORITY.index(x.dataset))):
        status, reasons = classify(r, conflicts)
        rows.append(_row(r, status, reasons, dd.merged.get(f"{r.dataset}:{r.claim_id}", [])))

    before_by_ds = Counter(r.dataset for r in records)
    after_by_ds = Counter(r["originating_dataset"] for r in rows)
    coverage = compute_coverage(questions, rows)
    tree_comparison = compare_with_tree(coverage)

    return {
        "schema": MANIFEST_SCHEMA,
        "datasets": [vars(s) for s in (summaries or [])],
        "counts": {
            "before_dedupe": dd.before, "after_dedupe": dd.after,
            "exact_duplicates_removed": dd.before - dd.after,
            "before_by_dataset": dict(before_by_ds), "after_by_dataset": dict(after_by_ds),
            "by_status": {s: sum(1 for r in rows if r["status"] == s) for s in STATUSES},
            "by_dataset_and_status": {
                d: {s: sum(1 for r in rows if r["originating_dataset"] == d and r["status"] == s) for s in STATUSES}
                for d in paths.DATASET_PRIORITY},
        },
        "dedupe_log": [{"retained": k, "collapsed": v} for k, v in sorted(dd.merged.items())],
        "claims": rows,
        "coverage": coverage,
        "tree_comparison": tree_comparison,
    }


def render_report(result: dict) -> str:
    c, cov = result["counts"], result["coverage"]
    L = ["# Phase 2 - Checkpoint 1 inventory", "",
         "Generated by `python -m phase2.build`. Read-only: no research, no Supabase, no Production change.", "",
         "## Datasets found", ""]
    for d in result["datasets"]:
        L.append(f"- **{d['dataset']}** - available={d['available']}, claim rows={d['claim_rows']}, "
                 f"source rows={d['source_rows']}; files: {', '.join(d['files'])}")
        L += [f"  - {n}" for n in d["notes"]]
    L += ["", "## Counts", "",
          f"- Before exact dedupe: **{c['before_dedupe']}** ({c['before_by_dataset']})",
          f"- After exact dedupe: **{c['after_dedupe']}** ({c['after_by_dataset']})",
          f"- Exact duplicates removed: **{c['exact_duplicates_removed']}**", "",
          "## Validation status (after dedupe)", ""]
    L += [f"- {s}: {n}" for s, n in c["by_status"].items()]
    L += ["", "## Phase-2 candidates (uc-evidence-expansion)", ""]
    cands = [r for r in result["claims"] if r["originating_dataset"] == paths.DS_EXPANSION]
    L.append(f"Discovered **{len(cands)}** candidate claims.")
    L.append("")
    for r in cands:
        L.append(f"- **{r['claim_id']}** ({r['source_id']}, {r['applicability_class']}, {r['status']}): "
                 f"{(r['claim_text'] or '')[:160]}")
    L += ["", "## Coverage of the 39 patient questions", ""]
    for scope, t in cov["scopes"].items():
        a, lf = t["all_39"], t["leaf_level_3"]
        L.append(f"- **{scope}**: all 39 -> covered {a['covered']}, partial {a['partial']}, not covered "
                 f"{a['not_covered']}; leaf (27) -> covered {lf['covered']}, partial {lf['partial']}, "
                 f"not covered {lf['not_covered']}")
    return "\n".join(L) + "\n"


def write_outputs(result: dict, out_dir: Path = paths.OUTPUT_DIR) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    manifest = {k: result[k] for k in ("schema", "datasets", "counts", "dedupe_log", "claims")}
    files = {
        "manifest.json": manifest,
        "coverage.json": result["coverage"],
        "tree-disagreement.json": result["tree_comparison"],
    }
    written = []
    (out_dir / "inventory-report.md").write_text(render_report(result))
    written.append(out_dir / "inventory-report.md")
    for name, obj in files.items():
        p = out_dir / name
        p.write_text(json.dumps(obj, indent=2, sort_keys=True, ensure_ascii=False) + "\n")
        written.append(p)
    return written


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    result = build()
    print(json.dumps({"counts": result["counts"],
                      "coverage": result["coverage"]["scopes"]}, indent=2))
    if not args.check:
        for p in write_outputs(result):
            print("wrote", p)


if __name__ == "__main__":
    main()
